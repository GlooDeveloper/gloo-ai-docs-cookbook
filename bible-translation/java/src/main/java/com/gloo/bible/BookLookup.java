    private static final Map<String, String> CASEFOLDED_BOOK_IDS = buildCasefoldedMap();

    private static Map<String, String> buildCasefoldedMap() {
        Map<String, String> map = new HashMap<>();
        for (Map.Entry<String, String> entry : BOOK_IDS.entrySet()) {
            map.put(entry.getKey().toLowerCase(Locale.ROOT), entry.getValue());
        }
        return map;
    }

    /**
     * Returns the USFM book ID for a known book name, or null if unknown.
     * Lookup is case-insensitive.
     */
    public static String lookup(String bookName) {
        return CASEFOLDED_BOOK_IDS.get(bookName.toLowerCase(Locale.ROOT));
    }
